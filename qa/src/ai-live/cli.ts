/**
 * The LIVE AI result statement, checked end to end on a deployed environment.
 *
 *   railway run --environment <env> --service Assessment npm run qa:ai-live -- --slug=<funnel> [flags]
 *
 * The eval (qa:ai-eval) compares models on a prompt nobody is using yet. This pass asks
 * the other question: is what respondents get RIGHT NOW the thing that was decided, and
 * does it come out right? Five parts, each one a separate claim:
 *
 *   1. config     the funnel's workspace resolves the expected model and prompt version,
 *                 the version's text is byte for byte the reviewed prompt file, the word
 *                 window is 70 to 100, and the DEPLOYED commit carries a token ceiling
 *                 high enough for a thinking model (read from git at the deployed SHA)
 *   2. statements real respondents of the funnel, round-robin across bands, generated by
 *                 the app's OWN function with the funnel's own tenant and version, then
 *                 scored by the deterministic checks and (unless --no-judge) the judge
 *   3. metering   every one of those calls left exactly one ai_usage row, on the right
 *                 workspace, model and key, and the per-workspace totals the AI usage
 *                 screen reads moved by exactly what this run spent
 *   4. screen     the deployed /platform/ai-usage page, signed in as the QA super admin:
 *                 it opens, the workspace's numbers match the data, dates are DD-MM-YYYY
 *   5. deployed   inside the workspace, the AI page's "Test connection" runs on the
 *                 deployed server with the saved config: it answers in time, the
 *                 statement is whole, and its usage row names the expected model
 *
 * 🟢 WHAT IT NEVER DOES: drive the funnel. A completion fires the workspace's webhooks
 * (and a live funnel's webhooks can reach Meta through the owner's automations), so the
 * statement is generated by calling the same function completion calls, with the same
 * arguments, on respondents who already exist. Nothing is written to their records.
 *
 * 🟡 WHAT IT DOES WRITE: the app's own meter rows (one per statement, that is the thing
 * under test), and entering the workspace in part 5 is recorded in the audit log, the
 * same as when the owner does it.
 *
 * Flags:
 *   --slug=<funnel>          required
 *   --cases=12               real respondents
 *   --expect-model=<id>      default claude-sonnet-5-5
 *   --expect-prompt=<name>   prompt file in qa/src/ai-eval/prompts/ (default v6-1)
 *   --no-judge               skip the judge
 *   --no-browser             skip parts 4 and 5
 *   --i-know-this-is-prod    required on a host that is not staging
 */
