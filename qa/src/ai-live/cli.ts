function arg(name: string, fallback?: string): string | undefined {
  const hit = process.argv.find((a) => a === `--${name}` || a.startsWith(`--${name}=`));
  if (!hit) return fallback;
  return hit.includes("=") ? hit.slice(hit.indexOf("=") + 1) : "true";
}

const pass = (what: string, observed?: string): Check => ({ verdict: "pass", what, observed });
const fail = (what: string, observed?: string): Check => ({ verdict: "fail", what, observed });
const warn = (what: string, observed: string): Check => ({ verdict: "warn", what, observed });
const ok = (what: string, cond: boolean, expected: string, observed: string): Check => ({
  verdict: cond ? "pass" : "fail",
  what,
  expected,
  observed,
});

/** Statements are 70 to 100 words; anything past this many output tokens is a model thinking far too long. */
const THINKING_WARN_TOKENS = 3000;
/** The app's own request timeout (generate.ts TIMEOUT_MS), read from the deployed commit. A statement slower than this is lost. */
let appTimeoutMs = 30_000;
/** A statement past two thirds of the timeout is one bad day from being lost. */
const SLOW_SHARE = 2 / 3;

interface Part {
  id: string;
  title: string;
  checks: Check[];
}

interface StatementRow {
  n: number;
  bandLevel: string | null;
  ms: number;
  words: number;
  text: string;
  error: string | null;
  usage: { model: string; inputTokens: number; outputTokens: number; onPlatformKey: boolean; costMicroUsd: number } | null;
  checks: CheckResult[];
  judge?: JudgeVerdict;
}

const normalise = (s: string) => s.replace(/\r\n/g, "\n").trim();

/** The newest usage row for this workspace and purpose since `since`, polled: the app records it without awaiting. */
async function usageRowSince(tenantId: string | null, purpose: string, since: Date, notIds: Set<string>) {
  for (let i = 0; i < 20; i++) {
    const row = await prisma.aiUsage.findFirst({
      where: { tenantId, purpose, createdAt: { gte: since }, id: { notIn: [...notIds] } },
      orderBy: { createdAt: "asc" },
      select: { id: true, model: true, inputTokens: true, outputTokens: true, onPlatformKey: true },
    });
    if (row) return row;
    await new Promise((r) => setTimeout(r, 500));
  }
  return null;
}

/** Round-robin real completions across bands, preview rows excluded, as the eval does. */
async function loadRespondents(funnelId: string, title: string, n: number): Promise<Array<{ input: StatementInput; bandLevel: string | null }>> {
  const subs = await prisma.submission.findMany({
    where: { assessmentId: funnelId, status: "COMPLETED", isPreview: false },
    orderBy: { createdAt: "desc" },
    take: 150,
    select: { id: true, leadFirstName: true, leadProfession: true, resultSnapshot: true },
  });
  const byBand = new Map<string, typeof subs>();
  for (const s of subs) {
    const snap = s.resultSnapshot as unknown as ResultSnapshot | null;
    if (!snap || typeof snap.scoreRaw !== "number" || !Array.isArray(snap.categories)) continue;
    const k = snap.resultBandLevel ?? snap.resultBand ?? "?";
    byBand.set(k, [...(byBand.get(k) ?? []), s]);
  }
  const picked: typeof subs = [];
  while (picked.length < n && [...byBand.values()].some((l) => l.length > 0)) {
    for (const l of byBand.values()) {
      const s = l.shift();
      if (s && picked.length < n) picked.push(s);
    }
  }
  const out: Array<{ input: StatementInput; bandLevel: string | null }> = [];
  for (const s of picked) {
    const snap = s.resultSnapshot as unknown as ResultSnapshot;
    const breakdown = await getSubmissionQuestionBreakdown(s.id);
    const qByCat = new Map(breakdown.map((b) => [b.name, b.questions]));
    out.push({
      bandLevel: snap.resultBandLevel ?? null,
      input: {
        firstName: s.leadFirstName,
        profession: s.leadProfession,
        assessmentTitle: title,
        scoreRaw: snap.scoreRaw,
        max: snap.max,
        percentage: snap.scorePercent,
        band: snap.resultBand,
        bandLevel: snap.resultBandLevel ?? null,
        categories: snap.categories.map((c) => ({
          name: c.name,
          score: c.score,
          max: c.max,
          band: c.band,
          meaning: c.meaning,
          questions: qByCat.get(c.name) ?? [],
        })),
      },
    });
  }
  return out;
}

/** The statement was not cut off: it ends a sentence and used less than the ceiling. */
function inferredStop(text: string, outputTokens: number | null, ceiling: number | null): string {
  const endsSentence = /[.?]["')\]]?\s*$/.test(text.trim());
  if (!endsSentence) return "max_tokens";
  if (outputTokens != null && ceiling != null && outputTokens >= ceiling) return "max_tokens";
  return "end_turn";
}

/** Enter one named workspace from the console. Cookie only; the product's banner confirms it. */
async function enterTenantNamed(page: Page, baseUrl: string, name: string, slug: string | null): Promise<boolean> {
  await page.goto(`${baseUrl}/platform`, { waitUntil: "domcontentloaded", timeout: 60_000 });
  await page.waitForLoadState("networkidle", { timeout: 15_000 }).catch(() => {});
  const row = page
    .locator("tr")
    .filter({ hasText: slug ?? name })
    .filter({ has: page.getByRole("button", { name: /^Enter/ }) })
    .first();
  if ((await row.count()) === 0) return false;
  const enter = row.getByRole("button", { name: /^Enter/ }).first();
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    await enter.click().catch(() => {});
    // Wait for the redirect the server action performs, never for the network to go quiet:
    // the next navigation would abort the action and the cookie would never be written.
    const moved = await page
      .waitForURL((u) => u.pathname === "/admin", { timeout: 20_000 })
      .then(() => true)
      .catch(() => false);
    if (moved) break;
    await page.waitForTimeout(2000);
  }
  const banner = await page.locator("body").innerText().catch(() => "");
  return /Acting as tenant/i.test(banner) && banner.includes(name);
}

async function exitTenant(page: Page): Promise<void> {
  const exit = page.getByRole("button", { name: /Exit to platform/i }).first();
  if ((await exit.count()) > 0) {
    await exit.click().catch(() => {});
    await page.waitForURL((u) => u.pathname === "/platform", { timeout: 20_000 }).catch(() => {});
  }
}

async function main(): Promise<number> {
  const env = loadQaEnv();
  const slug = arg("slug");
  const nCases = Number(arg("cases", "12"));
  const expectModel = arg("expect-model", "claude-sonnet-5-5") ?? "claude-sonnet-5-5";
  const promptName = arg("expect-prompt", "v6-1") ?? "v6-1";
  const useJudge = arg("no-judge") !== "true";
  const useBrowser = arg("no-browser") !== "true";
  if (!slug) {
    console.log("Pass --slug=<funnel>.");
    return 2;
  }
  if (env.looksLikeProd && arg("i-know-this-is-prod") !== "true") {
    console.log(`${env.baseUrl} does not look like staging. This pass makes real AI calls on the workspace's key; pass --i-know-this-is-prod.`);
    return 2;
  }

  const started = new Date();
  const parts: Part[] = [];
  console.log(`\nLive AI statement on ${env.baseUrl}  funnel: ${slug}\n`);

  // ---------------------------------------------------------------- 1. config
  const config: Part = { id: "config", title: "Configuration the funnel resolves", checks: [] };
  parts.push(config);
  const funnel = await prisma.assessment.findUnique({
    where: { slug },
    select: { id: true, slug: true, title: true, tenantId: true, aiPromptVersionId: true, status: true },
  });
  if (!funnel) {
    console.log(`No funnel with slug ${slug}.`);
    return 2;
  }
  const tenant = funnel.tenantId
    ? await prisma.tenant.findUnique({ where: { id: funnel.tenantId }, select: { name: true, slug: true } })
    : null;
  const tenantName = tenant?.name ?? "Platform";
  const cfg = await getAiConfig(funnel.tenantId);
  config.checks.push(ok("AI is enabled with a key for the funnel's workspace", !!cfg, "a config", cfg ? `${cfg.provider}` : "none"));
  if (!cfg) return finish(parts, started, env.baseUrl, slug, []);
  config.checks.push(ok("the workspace generates with the expected model", cfg.model === expectModel, expectModel, cfg.model));
  config.checks.push(ok("the model has a list price, so its spend can be shown", isPriced(cfg.model), "priced", isPriced(cfg.model) ? "priced" : "no rate"));
  const version = await resolvePromptVersion(funnel.aiPromptVersionId ?? cfg.promptVersion, funnel.tenantId);
  const expectedText = normalise(readFileSync(join(QA_ROOT, "src", "ai-eval", "prompts", `${promptName}.txt`), "utf8"));
  // The resolved version carries a builder, not its text, so the text is read from its row.
  const versionRow = version
    ? await prisma.aiPromptVersion.findFirst({ where: { id: version.id, tenantId: funnel.tenantId }, select: { instructions: true } })
    : null;
  const same = !!versionRow && normalise(versionRow.instructions) === expectedText;
  config.checks.push(
    ok(
      `the funnel resolves the reviewed prompt (${promptName}.txt)`,
      same,
      "byte for byte",
      !version ? "no version" : `${version.label}${versionRow ? (same ? ", identical" : ", text differs") : ", a built-in code version"}`,
    ),
  );
  config.checks.push(
    ok(
      "the funnel inherits the workspace default rather than pinning an old version",
      !funnel.aiPromptVersionId || funnel.aiPromptVersionId === cfg.promptVersion,
      "inherits",
      funnel.aiPromptVersionId ? `pinned to ${funnel.aiPromptVersionId}` : "inherits",
    ),
  );
  const words = await getWordWindow(funnel.tenantId);
  config.checks.push(ok("the word window is 70 to 100", words.min === 70 && words.max === 100, "70-100", `${words.min}-${words.max}`));

  // Other AI funnels in the same workspace that pin a version: not wrong, but worth seeing.
  const pinned = await prisma.assessment.findMany({
    where: { tenantId: funnel.tenantId, status: "PUBLISHED", aiPromptVersionId: { not: null }, NOT: { id: funnel.id } },
    select: { slug: true, aiPromptVersionId: true },
  });
  const pinnedElsewhere = pinned.filter((p) => p.aiPromptVersionId !== cfg.promptVersion);
  if (pinnedElsewhere.length > 0) {
    config.checks.push(
      warn(
        "other published funnels in this workspace pin an older prompt",
        pinnedElsewhere.map((p) => p.slug).join(", "),
      ),
    );
  }

  // The ceiling the DEPLOYED code carries, read from git at the commit /api/version reports.
  let ceiling: number | null = null;
  try {
    const res = await fetch(`${env.baseUrl}/api/version`, { signal: AbortSignal.timeout(20_000) });
    const deployed = ((await res.json()) as { commit?: string }).commit ?? "";
    execFileSync("git", ["fetch", "-q", "origin"], { cwd: REPO_ROOT, stdio: "ignore" });
    const src = execFileSync("git", ["show", `${deployed}:src/lib/ai/generate.ts`], { cwd: REPO_ROOT, encoding: "utf8" });
    ceiling = Number(/const MAX_TOKENS = ([\d_]+)/.exec(src)?.[1]?.replace(/_/g, "") ?? NaN);
    const deployedTimeout = Number(/const TIMEOUT_MS = ([\d_]+)/.exec(src)?.[1]?.replace(/_/g, "") ?? NaN);
    if (Number.isFinite(deployedTimeout)) appTimeoutMs = deployedTimeout;
    config.checks.push(pass("the deployed request timeout was read", `${appTimeoutMs} ms`));
    config.checks.push(
      ok(
        "the deployed code's token ceiling leaves room for thinking",
        Number.isFinite(ceiling) && ceiling >= 4000,
        ">= 4000",
        `${ceiling} at ${deployed.slice(0, 7)}`,
      ),
    );
  } catch (e) {
    config.checks.push(fail("the deployed token ceiling could be read", e instanceof Error ? e.message.split("\n")[0] : String(e)));
  }

  // ---------------------------------------------------------------- 2. statements + 3. metering
  const statements: Part = { id: "statements", title: "Statements on real respondents, through the app's own function", checks: [] };
  const metering: Part = { id: "metering", title: "Every call metered, and the screen's totals move by exactly that", checks: [] };
  parts.push(statements, metering);

  const before = await getAiUsageByTenant();
  const beforeRow = before.rows.find((r) => r.tenantId === funnel.tenantId);
  const respondents = await loadRespondents(funnel.id, funnel.title, nCases);
  statements.checks.push(ok(`${nCases} real respondents to test on`, respondents.length === nCases, String(nCases), String(respondents.length)));

  const rows: StatementRow[] = [];
  const seen = new Set<string>();
  // Serially, on purpose: one call at a time gives the latency a respondent actually waits,
  // and lets each meter row be matched to the call that made it.
  for (const [i, r] of respondents.entries()) {
    const t0 = new Date();
    const { text, error } = await generatePersonalStatementResult(r.input, funnel.tenantId, funnel.aiPromptVersionId);
    const ms = Date.now() - t0.getTime();
    const u = await usageRowSince(funnel.tenantId, "statement", t0, seen);
    if (u) seen.add(u.id);
    const t = text ?? "";
    rows.push({
      n: i + 1,
      bandLevel: r.bandLevel,
      ms,
      words: wordCount(t),
      text: t,
      error,
      usage: u
        ? { model: u.model, inputTokens: u.inputTokens, outputTokens: u.outputTokens, onPlatformKey: u.onPlatformKey, costMicroUsd: costMicroUsd(u.model, u.inputTokens, u.outputTokens) }
        : null,
      checks: scoreStatement(t, r.input, { minWords: words.min, maxWords: words.max, stopReason: inferredStop(t, u?.outputTokens ?? null, ceiling) }),
    });
    console.log(`  statement ${i + 1}/${respondents.length}: ${error ? `error ${error.slice(0, 80)}` : `${wordCount(t)} words, ${ms} ms, ${u?.outputTokens ?? "?"} out`}`);
  }
  if (useJudge) {
    await Promise.all(
      rows.map(async (row, i) => {
        const r = respondents[i];
        if (row.text && r) row.judge = await judgeStatement(cfg.apiKey, r.input, row.text);
      }),
    );
  }

  const generated = rows.filter((r) => r.text && !r.error);
  statements.checks.push(ok("every call returned a statement", generated.length === rows.length, String(rows.length), String(generated.length)));
  for (const r of rows.filter((x) => x.error)) statements.checks.push(fail(`statement ${r.n} failed`, r.error ?? ""));
  const slowest = Math.max(0, ...rows.map((r) => r.ms));
  statements.checks.push(ok(`every statement arrives inside the app's ${appTimeoutMs / 1000} s timeout`, slowest < appTimeoutMs, `< ${appTimeoutMs} ms`, `slowest ${slowest} ms`));
  if (slowest >= appTimeoutMs * SLOW_SHARE) statements.checks.push(warn("a statement used over two thirds of the timeout", `${slowest} of ${appTimeoutMs} ms`));

  // Every deterministic check, across every statement: a check fails if any statement fails it.
  const checkIds = rows[0]?.checks.map((c) => c.id) ?? [];
  for (const id of checkIds) {
    const failing = rows.filter((r) => !r.checks.find((c) => c.id === id)?.pass);
    const label = rows[0]?.checks.find((c) => c.id === id)?.label ?? id;
    statements.checks.push(
      ok(
        label,
        failing.length === 0,
        `${rows.length}/${rows.length}`,
        failing.length === 0
          ? `${rows.length}/${rows.length}`
          : `${rows.length - failing.length}/${rows.length}; failing ${failing.map((f) => `#${f.n}${f.checks.find((c) => c.id === id)?.detail ? ` (${f.checks.find((c) => c.id === id)?.detail})` : ""}`).join(", ")}`,
      ),
    );
  }

  // Stock lines across DIFFERENT people: the same 6-word run in two statements means
  // neither reads as written for its reader.
  // The handoff (the sentences pointing at the video and the play button) is left out:
  // each reader sees one statement, so a shared handoff is invisible to every one of them,
  // while a shared line about their LIFE is the thing that reads as a template.
  const body = (t: string) =>
    t
      .split(/(?<=[.?])\s+/)
      .filter((s) => !/\b(video|play|twelve minutes|minutes long)\b/i.test(s))
      .join(" ");
  const shared = new Map<string, number>();
  for (let a = 0; a < generated.length; a++)
    for (let b = a + 1; b < generated.length; b++)
      for (const g of sharedRuns(body(generated[a]?.text ?? ""), body(generated[b]?.text ?? ""))) shared.set(g, (shared.get(g) ?? 0) + 1);
  const stock = [...shared.entries()].sort((x, y) => y[1] - x[1]);
  if (stock.length > 0) statements.checks.push(warn("6-word runs about their life shared between different people", stock.slice(0, 5).map(([g, n]) => `"${g}" x${n}`).join("; ")));
  else statements.checks.push(pass("no line about their life is shared between different people"));
  const handoffs = new Set(generated.map((g) => (g.text.split(/(?<=[.?])\s+/).find((s) => /\bvideo\b/i.test(s)) ?? "").trim()));
  statements.checks.push(pass("distinct handoff sentences (informational: the prompt asks for variety)", `${handoffs.size} across ${generated.length}`));

  if (useJudge) {
    const judged = rows.filter((r) => r.judge && !r.judge.error);
    const clean = judged.filter((r) => r.judge?.clean).length;
    const byRule = new Map<string, string[]>();
    for (const r of judged) for (const iss of r.judge?.issues ?? []) byRule.set(iss.rule, [...(byRule.get(iss.rule) ?? []), `#${r.n} "${iss.quote}"`]);
    const spec = judged.map((r) => r.judge?.specific).filter((s): s is number => typeof s === "number");
    const avgSpec = spec.length ? spec.reduce((a, b) => a + b, 0) / spec.length : 0;
    // The judge is a model, not a rule, so its findings are cautions: read the quotes.
    statements.checks.push(clean === judged.length ? pass("judge: every statement clean", `${clean}/${judged.length}`) : warn("judge: statements with a flagged sentence", `${judged.length - clean}/${judged.length}`));
    for (const [rule, quotes] of byRule) statements.checks.push(warn(`judge flagged "${rule}"`, quotes.slice(0, 4).join("; ")));
    statements.checks.push(ok("judge: average specificity at least 4 of 5", avgSpec >= 4, ">= 4.0", avgSpec.toFixed(1)));
  }

  // Metering.
  const metered = rows.filter((r) => r.usage);
  metering.checks.push(ok("each statement left exactly one usage row", metered.length === rows.length, String(rows.length), String(metered.length)));
  const wrongModel = metered.filter((r) => r.usage?.model !== expectModel);
  metering.checks.push(ok("each usage row names the expected model", wrongModel.length === 0, expectModel, wrongModel.length ? wrongModel.map((r) => r.usage?.model).join(", ") : "all match"));
  const keyExpected = !(await prisma.appSetting.findFirst({ where: { tenantId: funnel.tenantId }, select: { aiClaudeKeyEnc: true } }))?.aiClaudeKeyEnc;
  const wrongKey = metered.filter((r) => r.usage?.onPlatformKey !== keyExpected);
  metering.checks.push(
    ok(
      "each usage row says whose key paid",
      wrongKey.length === 0,
      keyExpected ? "the platform's key" : "the workspace's own key",
      wrongKey.length ? `${wrongKey.length} row(s) disagree` : "all match",
    ),
  );
  const outs = metered.map((r) => r.usage?.outputTokens ?? 0);
  const over900 = outs.filter((o) => o > 900).length;
  metering.checks.push(
    over900 > 0
      ? pass("statements that would have been cut off at the old 900 ceiling now complete", `${over900}/${outs.length} used more than 900 output tokens`)
      : pass("no statement needed more than 900 output tokens", `max ${Math.max(0, ...outs)}`),
  );
  const heavy = outs.filter((o) => o > THINKING_WARN_TOKENS).length;
  if (heavy > 0) metering.checks.push(warn(`statements over ${THINKING_WARN_TOKENS} output tokens (close to the ceiling)`, `${heavy}/${outs.length}`));
  const spent = metered.reduce((s, r) => s + (r.usage?.costMicroUsd ?? 0), 0);
  const tokIn = metered.reduce((s, r) => s + (r.usage?.inputTokens ?? 0), 0);
  const tokOut = metered.reduce((s, r) => s + (r.usage?.outputTokens ?? 0), 0);

  const after = await getAiUsageByTenant();
  const afterRow = after.rows.find((r) => r.tenantId === funnel.tenantId);
  const dCalls = (afterRow?.calls ?? 0) - (beforeRow?.calls ?? 0);
  const dIn = (afterRow?.inputTokens ?? 0) - (beforeRow?.inputTokens ?? 0);
  const dOut = (afterRow?.outputTokens ?? 0) - (beforeRow?.outputTokens ?? 0);
  metering.checks.push(ok("the workspace's call count moved by exactly this run", dCalls === rows.length, `+${rows.length}`, `+${dCalls}`));
  metering.checks.push(ok("its token totals moved by exactly this run", dIn === tokIn && dOut === tokOut, `+${tokIn} / +${tokOut}`, `+${dIn} / +${dOut}`));
  const dMoney = keyExpected
    ? (afterRow?.platformMicroUsd ?? 0) - (beforeRow?.platformMicroUsd ?? 0)
    : (afterRow?.ownKeyMicroUsd ?? 0) - (beforeRow?.ownKeyMicroUsd ?? 0);
  metering.checks.push(ok("its spend moved by exactly this run's list-price cost", dMoney === spent, usdFromMicro(spent), usdFromMicro(dMoney)));
  metering.checks.push(
    ok(
      "the month column moved too",
      (afterRow?.monthCalls ?? 0) - (beforeRow?.monthCalls ?? 0) === rows.length,
      `+${rows.length}`,
      `+${(afterRow?.monthCalls ?? 0) - (beforeRow?.monthCalls ?? 0)}`,
    ),
  );
  metering.checks.push(ok("the model is listed against the workspace", !!afterRow?.models.includes(expectModel), expectModel, afterRow?.models.join(", ") ?? "no row"));

  // ---------------------------------------------------------------- 4 + 5. browser
  if (useBrowser) {
    const screen: Part = { id: "screen", title: "The deployed AI usage screen", checks: [] };
    const deployed: Part = { id: "deployed", title: "The deployed server's own statement (Test connection, inside the workspace)", checks: [] };
    parts.push(screen, deployed);
    if (!env.adminEmail || !env.adminPassword) {
      screen.checks.push(warn("skipped", "no QA_ADMIN_EMAIL / QA_ADMIN_PASSWORD in the env file"));
    } else {
      const browser = await chromium.launch({ headless: arg("headed") !== "true" });
      const context = await blockMeta(await browser.newContext({ userAgent: CHROME_UA, viewport: { width: 1280, height: 900 }, locale: "en-IN" }));
      const page = await context.newPage();
      const outDir = reportDir(started);
      try {
        const problem = await signIn(page, env.baseUrl, env.adminEmail, env.adminPassword);
        screen.checks.push(problem ? fail("the QA super admin signs in", problem) : pass("the QA super admin signs in"));
        if (!problem) {
          // The menu offers the screen.
          await page.goto(`${env.baseUrl}/platform`, { waitUntil: "domcontentloaded", timeout: 60_000 });
          await page.waitForLoadState("networkidle", { timeout: 15_000 }).catch(() => {});
          const link = page.locator("a[href='/platform/ai-usage']");
          screen.checks.push(ok("the Platform menu links to AI usage", (await link.count()) > 0, "a link", `${await link.count()} link(s)`));

          const path = "/platform/ai-usage";
          const v = await visit(page, env.baseUrl, path);
          screen.checks.push(...arrived(v, path), ...datesAreIndian(v, path));
          const h1 = (await page.locator("main h1").first().innerText().catch(() => "")).trim();
          screen.checks.push(ok("the page is titled AI usage", h1 === "AI usage", "AI usage", h1 || "no heading"));
          const fresh = await getAiUsageByTenant();
          const want = fresh.rows.find((r) => r.tenantId === funnel.tenantId);
          const tr = page.locator("tbody tr").filter({ hasText: tenantName }).first();
          const cells = (await tr.count()) ? await tr.locator("td").allInnerTexts() : [];
          screen.checks.push(ok(`the ${tenantName} row is on the screen`, cells.length >= 8, "a row", cells.length ? "present" : "missing"));
          if (cells.length >= 8 && want) {
            const n = (x: number) => x.toLocaleString("en-IN");
            screen.checks.push(ok("its call count matches the data", cells[1]?.trim() === n(want.calls), n(want.calls), cells[1]?.trim() ?? ""));
            screen.checks.push(
              ok("its token counts match the data", cells[2]?.replace(/\s+/g, " ").trim() === `${n(want.inputTokens)} / ${n(want.outputTokens)}`, `${n(want.inputTokens)} / ${n(want.outputTokens)}`, cells[2]?.trim() ?? ""),
            );
            const ownCell = want.ownKeyMicroUsd > 0 ? usdFromMicro(want.ownKeyMicroUsd) : "-";
            screen.checks.push(ok("its own-key spend matches the data", cells[5]?.trim() === ownCell, ownCell, cells[5]?.trim() ?? ""));
            screen.checks.push(ok("its models column names the expected model", !!cells[6]?.includes(expectModel), expectModel, cells[6]?.trim() ?? ""));
            screen.checks.push(ok("its last call is DD-MM-YYYY HH:MM", /^\d{2}-\d{2}-\d{4} \d{2}:\d{2}/.test(cells[7]?.trim() ?? ""), "DD-MM-YYYY HH:MM", cells[7]?.trim() ?? ""));
          }
          const foot = await page.locator("tfoot td").allInnerTexts().catch(() => [] as string[]);
          screen.checks.push(ok("the total row's calls match the data", foot[1]?.trim() === fresh.totals.calls.toLocaleString("en-IN"), fresh.totals.calls.toLocaleString("en-IN"), foot[1]?.trim() ?? "no footer"));
          await page.screenshot({ path: join(outDir, "ai-usage.png"), fullPage: true }).catch(() => {});

          // 5. Inside the workspace: the deployed server generates with the saved config.
          const entered = await enterTenantNamed(page, env.baseUrl, tenantName, tenant?.slug ?? null);
          deployed.checks.push(entered ? pass(`entered ${tenantName}`) : fail(`entered ${tenantName}`, "the console did not let the QA admin in"));
          if (entered) {
            try {
              const av = await visit(page, env.baseUrl, "/admin/ai");
              deployed.checks.push(...arrived(av, "/admin/ai"));
              const t0 = new Date();
              await page.getByRole("button", { name: /Test connection/ }).click();
              const result = page.locator("text=/Worked in \\d+ ms|Failed/").first();
              await result.waitFor({ timeout: 90_000 }).catch(() => {});
              const head = (await result.innerText().catch(() => "")).trim();
              const body = head.startsWith("Worked")
                ? ((await result.locator("xpath=following-sibling::p[1]").innerText().catch(() => "")) || "").trim()
                : "";
              const ms = Number(/Worked in (\d+) ms/.exec(head)?.[1] ?? NaN);
              deployed.checks.push(ok("Test connection works on the deployed server", head.startsWith("Worked"), "Worked in N ms", head.slice(0, 160) || "no answer in 90 s"));
              if (head.startsWith("Worked")) {
                deployed.checks.push(ok(`it answers inside the app's ${appTimeoutMs / 1000} s timeout`, ms < appTimeoutMs, `< ${appTimeoutMs} ms`, `${ms} ms`));
                const u = await usageRowSince(funnel.tenantId, "test", t0, new Set());
                deployed.checks.push(ok("its usage row names the expected model", u?.model === expectModel, expectModel, u?.model ?? "no row"));
                deployed.checks.push(ok("its usage row has real token counts", (u?.outputTokens ?? 0) > 0, "> 0", String(u?.outputTokens ?? 0)));
                const sample = (await builtInPromptsAllowed(funnel.tenantId)) ? PREVIEW_SAMPLE : NEUTRAL_SAMPLE;
                const sc = scoreStatement(body, sample, { minWords: words.min, maxWords: words.max, stopReason: inferredStop(body, u?.outputTokens ?? null, ceiling) });
                for (const c of sc) deployed.checks.push(ok(`sample statement: ${c.label}`, c.pass, "pass", c.pass ? "pass" : (c.detail ?? "fails")));
                rows.push({ n: 0, bandLevel: "sample", ms, words: wordCount(body), text: body, error: null, usage: u ? { ...u, costMicroUsd: costMicroUsd(u.model, u.inputTokens, u.outputTokens) } : null, checks: sc });
              }
              await page.screenshot({ path: join(outDir, "admin-ai-test.png"), fullPage: true }).catch(() => {});
            } finally {
              await exitTenant(page);
            }
            const out = await page.locator("body").innerText().catch(() => "");
            deployed.checks.push(ok("came back out of the workspace", !/Acting as tenant/i.test(out), "the platform console", /Acting as tenant/i.test(out) ? "still acting as the tenant" : "out"));
          }
        }
      } finally {
        await browser.close();
      }
    }
  }

  return finish(parts, started, env.baseUrl, slug, rows, { spent, tokIn, tokOut, statements: metered.length, expectModel });
}

function reportDir(started: Date): string {
  const dir = join(QA_ROOT, "reports", `ai-live-${started.toISOString().replace(/[:.]/g, "-")}`);
  mkdirSync(dir, { recursive: true });
  return dir;
}

function finish(
  parts: Part[],
  started: Date,
  baseUrl: string,
  slug: string,
  rows: StatementRow[],
  money?: { spent: number; tokIn: number; tokOut: number; statements: number; expectModel: string },
): number {
  const all = parts.flatMap((p) => p.checks);
  const count = (v: string) => all.filter((c) => c.verdict === v).length;
  const icon = (v: string) => (v === "pass" ? "🟢" : v === "warn" ? "🟡" : "🔴");
  const dir = reportDir(started);
  const lines: string[] = [];
  lines.push(`# Live AI statement check`, "");
  lines.push(`Host ${baseUrl}, funnel ${slug}, run ${started.toISOString()} (UTC).`, "");
  lines.push(`🟢 ${count("pass")} pass   🟡 ${count("warn")} warn   🔴 ${count("fail")} fail`, "");
  if (money && money.statements > 0) {
    lines.push(
      `Spend this run: ${money.statements} statements, ${money.tokIn} in / ${money.tokOut} out tokens, ${usdFromMicro(money.spent)} at list price, ${usdFromMicro(Math.round(money.spent / money.statements))} a statement (${money.expectModel}).`,
      "",
    );
  }
  for (const p of parts) {
    lines.push(`## ${p.title}`, "");
    for (const c of p.checks) {
      lines.push(`- ${icon(c.verdict)} ${c.what}${c.expected ? ` (expected ${c.expected})` : ""}${c.observed ? `: ${c.observed}` : ""}`);
    }
    lines.push("");
  }
  if (rows.length) {
    lines.push("## The statements", "", "First names are replaced with [Name].", "");
    for (const r of rows) {
      const failing = r.checks.filter((c) => !c.pass).map((c) => c.id);
      lines.push(
        `### ${r.n === 0 ? "Deployed Test connection (sample)" : `#${r.n}`} (${r.bandLevel ?? "?"}, ${r.words} words, ${r.ms} ms, ${r.usage ? `${r.usage.outputTokens} out, ${usdFromMicro(r.usage.costMicroUsd)}` : "no usage row"})`,
        "",
        `> ${redact(r.text) || r.error || "(empty)"}`,
        "",
        `Checks: ${failing.length ? `failing ${failing.join(", ")}` : "all pass"}${r.judge ? `. Judge: ${r.judge.clean ? "clean" : r.judge.issues.map((i) => `${i.rule} "${redact(i.quote)}"`).join("; ")}, specificity ${r.judge.specific ?? "?"}` : ""}`,
        "",
      );
    }
  }
  const md = lines.join("\n");
  writeFileSync(join(dir, "report.md"), md);
  writeFileSync(
    join(dir, "result.json"),
    JSON.stringify(
      {
        baseUrl,
        slug,
        startedAt: started.toISOString(),
        seconds: Math.round((Date.now() - started.getTime()) / 1000),
        pass: count("pass"),
        warn: count("warn"),
        fail: count("fail"),
        money,
        parts,
        statements: rows.map((r) => ({ ...r, text: redact(r.text) })),
      },
      null,
      2,
    ),
  );
  console.log("");
  for (const p of parts) {
    console.log(p.title);
    for (const c of p.checks) console.log(`  ${icon(c.verdict)} ${c.what}${c.observed ? `: ${c.observed}` : ""}`);
  }
  console.log(`\n🟢 ${count("pass")}  🟡 ${count("warn")}  🔴 ${count("fail")}   report: ${join(dir, "report.md")}`);
  return count("fail") > 0 ? 1 : 0;
}

/** A first name at the start of the statement is the respondent's; the report never carries it. */
function redact(text: string): string {
  const first = /^([A-Z][a-zA-Z'-]+)\b/.exec(text.trim())?.[1];
  return first ? text.split(first).join("[Name]") : text;
}

